/**
 * Level audit (CI): every level is valid and solvable; levels 1-10 cannot be failed by any order of taps;
 * no level can reach an impossible tray situation the player could not avoid (margin ≥ 1). Writes
 * docs/levels.md with the solver's numbers; exits 1 on any failure.
 */
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../src/puzzle/levels';
import { Puzzle, validateLevel } from '../src/puzzle/model';
import { solve } from '../src/puzzle/solver';

const rows: string[] = [];
let fails = 0;
for (const def of LEVELS) {
  const problems = validateLevel(def);
  const r = solve(new Puzzle(def));
  if (!r.complete) problems.push('solver did not finish');
  if (!r.solvable) problems.push('NOT SOLVABLE');
  if (def.id <= 10 && r.canFail) problems.push('levels 1-10 must be impossible to fail');
  if (r.margin < 1) problems.push(`tray margin ${r.margin} < 1`);
  if (problems.length) fails++;
  const screws = def.planks.reduce((n, p) => n + p.screws.length, 0);
  const colors = new Set(def.planks.flatMap((p) => p.screws)).size;
  const layers = new Set(def.planks.map((p) => p.layer)).size;
  const line = `| ${def.id} | ${def.object} | ${def.planks.length} | ${screws} | ${colors} | ${layers} | ${r.bestPeak}/${def.tray} | ${r.margin} | ${r.worstPeak} | ${r.canFail ? 'yes' : 'no'} | ${problems.join('; ') || 'ok'} |`;
  rows.push(line);
  console.log(line);
}
const md = `# Level audit\n\nGenerated by \`npm run audit\` (exhaustive solver over every order of taps).\n\n- **best peak**: the fewest tray slots a perfect order needs; **margin** = tray size − best peak\n- **worst peak**: the most tray slots any order of taps can fill; **can fail**: some order of taps loses\n\n| Level | Object | Planks | Screws | Colours | Layers | Best peak | Margin | Worst peak | Can fail | Result |\n|---|---|---|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
writeFileSync('docs/levels.md', md);
console.log(fails ? `\n${fails} level(s) failed the audit` : `\nall ${LEVELS.length} levels pass`);
process.exit(fails ? 1 : 0);
