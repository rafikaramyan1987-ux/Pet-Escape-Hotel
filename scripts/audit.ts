/**
 * Playtest audit: every room must be solved by the careful bot (all 3 bones), nobody may be seen in the first
 * 3 seconds without input, no guard may camp on the solution route, and the "human-like" noisy bot must win
 * often enough for the floor's difficulty. Writes docs/playtest.md; exits 1 on any failure.
 */
import { writeFileSync } from 'node:fs';
import { auditRoom, FLOOR_MIN_WIN } from '../src/core/audit';
import { ROOMS } from '../src/core/rooms';
import { parseLevel } from '../src/core/level';

const only = process.argv[2];
const seeds = Number(process.env.SEEDS ?? 24);
const rows: string[] = [];
let fails = 0;
for (const def of ROOMS) {
  if (only && !def.id.startsWith(only)) continue;
  const r = auditRoom(parseLevel(def), seeds);
  if (r.problems.length) fails++;
  const line = `| ${def.id} | ${def.name.en} | ${r.solved ? 'yes' : 'NO'} | ${r.bones}/3 | ${r.time.toFixed(1)} s | ${(r.winRate * 100).toFixed(0)}% (min ${(FLOOR_MIN_WIN[def.floor - 1] * 100).toFixed(0)}%) | ${r.problems.join('; ') || 'ok'} |`;
  rows.push(line);
  console.log(line);
}
const md = `# Playtest audit\n\nGenerated by \`npm run audit\` (${seeds} noisy-bot runs per room).\n\n| Room | Name | Solved | Bones | Bot time | Noisy win rate | Result |\n|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
if (!only) writeFileSync('docs/playtest.md', md);
console.log(fails ? `\n${fails} room(s) failed the audit` : '\nall rooms pass');
process.exit(fails ? 1 : 0);
