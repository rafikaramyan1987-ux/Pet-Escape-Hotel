/**
 * Level audit (CI): every level valid and solvable with tray margin ≥ 1 (no impossible tray situation for a
 * player who picks well); levels 1–10 impossible to fail by ANY order of taps; each 10th level a harder boss
 * and the level after it easier; a time limit per level keeps the solver honest. Writes docs/levels.md.
 */
import { writeFileSync } from 'node:fs';
import { randomFailRate } from '../src/puzzle/generate';
import { LEVELS } from '../src/puzzle/levels';
import { Puzzle, validateLevel } from '../src/puzzle/model';
import { hint, solve, type SolveResult } from '../src/puzzle/solver';

const TIME_LIMIT_MS = 4000;
const rows: string[] = [];
const fail: number[] = [];
let fails = 0;
const problemsOf: string[][] = [];
const results: SolveResult[] = [];
const botTaps: number[] = [];
for (const def of LEVELS) {
  const problems = validateLevel(def);
  const worst = def.id <= 10;
  const r = solve(new Puzzle(def), { worst, maxStates: 400_000 });
  if (!r.complete) problems.push('solver did not finish');
  if (!r.solvable) problems.push('NOT SOLVABLE');
  if (worst && (r.canFail || r.worstPeak >= def.tray)) problems.push('levels 1-10 must be impossible to fail');
  if (r.margin < 1) problems.push(`tray margin ${r.margin} < 1`);
  if (r.ms > TIME_LIMIT_MS) problems.push(`solver took ${r.ms} ms (limit ${TIME_LIMIT_MS})`);
  // the solver's best order, replayed move by move, must win without ever overfilling the tray
  const replay = new Puzzle(def);
  let peak = 0;
  for (const m of r.bestPath) {
    replay.tap(m);
    peak = Math.max(peak, replay.trayCount());
    if (replay.status === 'lost') break;
  }
  if (r.solvable && (replay.status !== 'won' || peak > r.bestPeak)) problems.push('best path replay does not win');
  // playtest bot: the in-game hint bot (as used by ?auto=1 and e2e) plays the level from scratch
  const bot = new Puzzle(def);
  let taps = 0;
  const t0 = Date.now();
  while (bot.status === 'play' && taps < 500) {
    const s = hint(bot);
    if (s < 0) break;
    bot.tap(s);
    taps++;
  }
  botTaps.push(taps);
  if (bot.status !== 'won') problems.push(`playtest bot ${bot.status} after ${taps} taps`);
  if (Date.now() - t0 > TIME_LIMIT_MS * 2) problems.push(`playtest bot too slow (${Date.now() - t0} ms)`);
  results.push(r);
  const rf = randomFailRate(def);
  fail.push(rf);
  problemsOf.push(problems);
}
// difficulty shape: bosses harder than the levels around them, the level after a boss easier than the boss
for (let i = 0; i < LEVELS.length; i++) {
  const id = LEVELS[i].id;
  if (id % 10 === 0 && id >= 20) {
    const around = [fail[i - 1], fail[i - 2], fail[i + 1]].filter((x) => x !== undefined);
    if (fail[i] < Math.max(...around)) problemsOf[i].push(`boss ${(fail[i] * 100).toFixed(0)}% not harder than neighbours`);
    if (fail[i + 1] !== undefined && fail[i + 1] >= fail[i]) problemsOf[i + 1].push('level after a boss must be easier');
  }
}
LEVELS.forEach((def, i) => {
  const r = results[i];
  const problems = problemsOf[i];
  if (problems.length) fails++;
  const screws = def.planks.reduce((n, p) => n + p.screws.length, 0);
  const colors = new Set(def.planks.flatMap((p) => p.screws)).size;
  const layers = new Set(def.planks.map((p) => p.layer)).size;
  const tag = def.id % 10 === 0 ? ' (boss)' : '';
  const line = `| ${def.id}${tag} | ${def.object} | ${def.planks.length} | ${screws} | ${colors} | ${layers} | ${r.bestPath.length} | ${botTaps[i]} | ${r.bestPeak}/${def.tray} | ${r.margin} | ${r.worstChecked ? `${r.worstPeak}${r.canFail ? ' (can fail)' : ' (cannot fail)'}` : '–'} | ${(fail[i] * 100).toFixed(0)}% | ${r.states} | ${r.ms} | ${problems.join('; ') || 'ok'} |`;
  rows.push(line);
  console.log(line);
});
const md = `# Level audit\n\nGenerated by \`npm run audit\` (CI fails on any problem).\n\n- **Solution**: taps in the solver's best order. **Best peak**: the fewest tray slots a perfect order needs; **margin** = tray size − best peak (always ≥ 1).\n- **Bot taps**: the playtest bot (the in-game hint, as used by the autoplay recordings and e2e) plays the level from scratch; it must win.
- **Worst peak** (levels 1–10): the most tray slots ANY order of taps can fill. All ten are "cannot fail".\n- **Random fail**: share of 300 games lost by tapping random free screws (a pessimistic forgiveness measure; people do much better). Bosses (every 10th) are the spikes, the next level drops back.\n- **States / ms**: solver work per level (time limit ${TIME_LIMIT_MS} ms).\n\n| Level | Object | Planks | Screws | Colours | Layers | Solution | Bot taps | Best peak | Margin | Worst peak | Random fail | States | ms | Result |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
writeFileSync('docs/levels.md', md);
console.log(fails ? `\n${fails} level(s) failed the audit` : `\nall ${LEVELS.length} levels pass`);
process.exit(fails ? 1 : 0);
